'use client'
import { useCallback, useEffect, useRef, useState } from 'react'
import { D, KB, answer, buildAlerts, type Answer } from '@/lib/data'
import { useApp } from './AppProvider'
import { ARR, Ico, cv } from './ui'

type SourceItem = { t: string; s: string; url?: string; excerpt?: string }
type Msg = {
  id: number
  role: 'u' | 'a'
  text?: string
  cites?: number[]
  sources?: SourceItem[]
  mode?: string
  typing?: boolean
  offline?: boolean
  known?: boolean
}
let uid = 0

export default function Assistant() {
  const { off, ver, pendingQ, setPendingQ } = useApp(); void ver
  const [msgs, setMsgs] = useState<Msg[]>([{ id: uid++, role: 'a', text: 'Hi! Ask me why an alert appeared. I answer only from the local library and show my sources.' }])
  const [q, setQ] = useState(''), [src, setSrc] = useState<SourceItem | null>(null)
  const [lastMode, setLastMode] = useState<string>('llm')
  const log = useRef<HTMLDivElement>(null), closeBtn = useRef<HTMLButtonElement>(null)

  const ask = useCallback(async (text: string) => {
    if (!text.trim()) return
    const tid = uid++, reading = { hr: D[29].hr, sleep: D[29].sleep }
    setMsgs((m) => [...m, { id: uid++, role: 'u', text }, { id: tid, role: 'a', typing: true }])
    let apiData: (Answer & { mode?: string; sources?: SourceItem[] }) | null = null
    try {
      const r = await fetch('/api/assistant/ask', {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify({ question: text, reading }),
      })
      if (r.ok) apiData = await r.json()
    } catch {}

    const fallback = answer(text, reading)
    const res = apiData ?? {
      ...fallback,
      mode: 'retrieval_only',
      sources: fallback.cites.map((i) => KB[i]),
    }
    if (res.mode) setLastMode(res.mode)
    setMsgs((m) =>
      m.map((x) =>
        x.id === tid
          ? {
              id: tid,
              role: 'a',
              text: res.text,
              cites: res.cites,
              sources: res.sources ?? res.cites?.map((i) => KB[i] ?? { t: `Source ${i + 1}`, s: 'Local library' }),
              mode: res.mode,
              known: res.known,
              offline: off,
            }
          : x
      )
    )
  }, [off])

  useEffect(() => { if (pendingQ) { ask(pendingQ); setPendingQ(null) } }, [pendingQ, ask, setPendingQ])
  useEffect(() => { log.current?.scrollTo({ top: 1e9 }) }, [msgs])
  useEffect(() => {
    if (src === null) return
    closeBtn.current?.focus()
    const k = (e: KeyboardEvent) => { if (e.key === 'Escape') setSrc(null) }
    addEventListener('keydown', k); return () => removeEventListener('keydown', k)
  }, [src])

  const send = () => { ask(q); setQ('') }
  const modeLabel = off
    ? 'Offline: answered from local library'
    : lastMode === 'llm'
    ? 'Local LLM + RAG (S1–S9)'
    : 'Retrieval-only RAG (S1–S9)'

  return (
    <section className="view on" id="assistant">
      <h1>AI assistant</h1><p className="sub">Answers come from the local scientific library and cite their sources.</p>
      <div className="card">
        <div className="pill" id="mode" style={{ ...cv('var(--ok)'), marginBottom: 12 }}>{modeLabel}</div>
        <div className="chat" id="chat" ref={log} role="log" aria-live="polite" aria-label="Conversation">
          {msgs.map((m) => (
            <div key={m.id} className={'b ' + m.role}>
              {m.typing ? <span className="dots" aria-label="Assistant is typing"><span /><span /><span /></span> : <>
                {m.text}
                {m.sources?.map((sItem, idx) => (
                  <button key={idx} className="cite" aria-label={`Open source ${idx + 1}`} onClick={() => setSrc(sItem)}>{idx + 1}</button>
                ))}
                {m.known && (
                  <div className="note">
                    {m.mode === 'llm' ? 'Generated by local LLM grounded in S1–S9. ' : 'Retrieved from local library (S1–S9). '}
                    Decision support only.
                  </div>
                )}
              </>}
            </div>
          ))}
        </div>
        <div className="chips" id="chips">{buildAlerts().map((a) => <button key={a.id} onClick={() => ask(a.q)}>{a.q}</button>)}</div>
        <div className="inp">
          <input id="q" placeholder="Ask about an alert or an indicator" aria-label="Ask the assistant" value={q} onChange={(e) => setQ(e.target.value)} onKeyDown={(e) => { if (e.key === 'Enter') send() }} />
          <button className="btn" id="send" onClick={send}>Ask<Ico d={ARR} cls="ar" /></button>
        </div>
        <p className="note">Decision support only. This is not a medical diagnosis. Grounded in Ammara’s curated scientific sources (S1–S9).</p>
      </div>
      <aside className={'drawer' + (src !== null ? ' on' : '')} id="dr" aria-label="Source" aria-hidden={src === null}>
        <button className="btn o" id="drx" ref={closeBtn} style={{ float: 'right' }} tabIndex={src === null ? -1 : 0} onClick={() => setSrc(null)}>Close</button>
        {src !== null && (
          <div id="drc">
            <h2 style={{ fontSize: 18, margin: '36px 0 8px' }}>{src.t}</h2>
            <p className="pill" style={cv('var(--acc)')}>{src.s}</p>
            <p style={{ marginTop: 14, color: 'var(--mut)' }}>
              {src.excerpt || 'Verified excerpt from the local spaceflight medical library.'}
            </p>
            {src.url && (
              <p style={{ marginTop: 12 }}>
                <a href={src.url} target="_blank" rel="noreferrer" style={{ color: 'var(--acc)', textDecoration: 'underline' }}>
                  {src.url}
                </a>
              </p>
            )}
          </div>
        )}
      </aside>
    </section>
  )
}
